import { API_BASE_URL } from '../services/api'

export const mapChamado = (c) => ({
  id: `TKT-${c.id}`,
  _id: c.id,
  titulo: c.titulo,
  title: c.titulo,
  descricao: c.descricao,
  description: c.descricao,
  category: c.categoria,
  priority: c.prioridade,
  status: c.status,
  requester: c.solicitante,
  email: c.email,
  setor: c.setor,
  bloco: c.bloco || c.andar,
  sala: c.sala,
  andar: c.andar,
  unidade: c.unidade,
  setorAtendimento: c.setorAtendimento,
  tecnicoResponsavelId: c.tecnicoResponsavelId,
  tecnicoResponsavelNome: c.tecnicoResponsavelNome,
  slaHoras: c.slaHoras,
  triagemJustificativa: c.triagemJustificativa,
  attachmentName: c.attachmentName,
  attachmentContentType: c.attachmentContentType,
  attachmentUrl: c.attachmentName ? `${API_BASE_URL}/chamados/${c.id}/anexo` : null,
  createdAt: new Date(c.createdAt),
  updatedAt: new Date(c.updatedAt),
  deletedAt: c.deletedAt ? new Date(c.deletedAt) : null,
  deletedBy: c.deletedBy,
})
